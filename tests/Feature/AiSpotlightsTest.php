<?php

namespace Tests\Feature;

use Illuminate\Foundation\Testing\RefreshDatabase;
use Tests\TestCase;

class AiSpotlightsTest extends TestCase
{
    use RefreshDatabase;

    public function test_homepage_displays_all_three_ai_spotlights_in_dedicated_row(): void
    {
        $response = $this->get('/');

        $response->assertStatus(200);
        $response->assertSee('Featured AI Platform Spotlights');
        $response->assertSee('AIApply');
        $response->assertSee('ANARA');
        $response->assertSee('Typeless');
        $response->assertSee('logo-aiapply.png');
        $response->assertSee('logo-anara.svg');
        $response->assertSee('logo-typeless.png');
        $response->assertSee(route('spotlights.iapply'));
        $response->assertSee(route('spotlights.anara'));
        $response->assertSee(route('spotlights.typeless'));
    }

    public function test_iapply_spotlight_page_renders_aiapply_co_with_offers_logos_and_deep_links(): void
    {
        $response = $this->get(route('spotlights.iapply'));

        $response->assertStatus(200);
        $response->assertSee('AIApply Review (2026)');
        $response->assertSee('Visit Official Site');
        $response->assertSee('Start Auto-Applying Now');
        $response->assertSee('logo-aiapply.png');
        $response->assertSee('https://www.aiapply.co/?via=aihubinsider');
        $response->assertSee('https://www.aiapply.co/auto-apply?via=aihubinsider');
        $response->assertSee('https://www.aiapply.co/resume-builder?via=aihubinsider');
        $response->assertSee('https://www.aiapply.co/students?via=aihubinsider');
        $response->assertSee('https://www.aiapply.co/tools?via=aihubinsider');
        $response->assertDontSee('?via=aihub"', false);
        $response->assertSee('id="spotlight-offer-modal"', false);
        $response->assertSee('data-spotlight-modal-close', false);
        $response->assertSee('popup-aiapply.jpg');
        $response->assertSee('Claim 30%–40% Bonus Offer');
        $response->assertSee('739,421+');
        $response->assertSee('id="evaluation-scorecard"', false);
        $response->assertSee('id="faq-section"', false);
        $response->assertSee('Will ATS systems flag resumes and cover letters generated by AIApply?');
    }

    public function test_anara_spotlight_page_renders_with_offers_logos_and_ref_links(): void
    {
        $response = $this->get(route('spotlights.anara'));

        $response->assertStatus(200);
        $response->assertSee('ANARA AI Review (2026)');
        $response->assertSee('Visit Official Site');
        $response->assertSee('Book Your Free Demo');
        $response->assertSee('logo-anara.svg');
        $response->assertSee('https://anara.com?via=aihub');
        $response->assertSee('id="spotlight-offer-modal"', false);
        $response->assertSee('popup-anara.jpg');
        $response->assertSee('Claim Free Enterprise Demo');
        $response->assertSee('Full Source Code & IP Ownership');
        $response->assertSee('id="evaluation-scorecard"', false);
        $response->assertSee('id="faq-section"', false);
        $response->assertSee('Do we truly keep 100% ownership of the generated code?');
    }

    public function test_typeless_spotlight_page_renders_with_offers_logos_and_deep_links(): void
    {
        $response = $this->get(route('spotlights.typeless'));

        $response->assertStatus(200);
        $response->assertSee('Typeless Review (2026)');
        $response->assertSee('Visit Official Site');
        $response->assertSee('Try Typeless Free Now');
        $response->assertSee('logo-typeless.png');
        $response->assertSee('https://www.typeless.com/?via=aihubb');
        $response->assertSee('https://www.typeless.com/pricing?via=aihubb');
        $response->assertSee('https://www.typeless.com/referral?via=aihubb');
        $response->assertSee('https://www.typeless.com/students?via=aihubb');
        $response->assertSee('typeless-preview.svg');
        $response->assertSee('id="spotlight-offer-modal"', false);
        $response->assertSee('popup-typeless.jpg');
        $response->assertSee('Claim $5 Bonus & 60% Off');
        $response->assertSee('220');
        $response->assertSee('Typeless Referral Bonus');
        $response->assertSee('Verified Student 50% Pro Discount');
        $response->assertSee('id="evaluation-scorecard"', false);
        $response->assertSee('id="faq-section"', false);
        $response->assertSee('How is Typeless different from built-in Apple or Windows voice dictation?');
    }

    public function test_sitemap_includes_all_three_spotlight_urls(): void
    {
        $response = $this->get(route('sitemap'));

        $response->assertStatus(200);
        $response->assertSee(route('spotlights.iapply'));
        $response->assertSee(route('spotlights.anara'));
        $response->assertSee(route('spotlights.typeless'));
    }

    public function test_dedicated_review_subdomains_render_each_spotlight_at_root_path(): void
    {
        $aiapplyResponse = $this->get('https://aiapplyreview.aihubinsider.com/');
        $aiapplyResponse->assertStatus(200);
        $aiapplyResponse->assertSee('AIApply Review (2026)');
        $aiapplyResponse->assertSee('aiapplyreview.aihubinsider.com');
        $aiapplyResponse->assertSee('https://www.aiapply.co/?via=aihubinsider');
        $aiapplyResponse->assertSee('href="https://aihubinsider.com"', false);
        $aiapplyResponse->assertSee('href="https://anarareview.aihubinsider.com"', false);
        $aiapplyResponse->assertSee('href="https://typelessreview.aihubinsider.com"', false);

        $anaraResponse = $this->get('https://anarareview.aihubinsider.com/');
        $anaraResponse->assertStatus(200);
        $anaraResponse->assertSee('ANARA AI Review (2026)');
        $anaraResponse->assertSee('anarareview.aihubinsider.com');
        $anaraResponse->assertSee('https://anara.com?via=aihub');

        $typelessResponse = $this->get('https://typelessreview.aihubinsider.com/');
        $typelessResponse->assertStatus(200);
        $typelessResponse->assertSee('Typeless Review (2026)');
        $typelessResponse->assertSee('typelessreview.aihubinsider.com');
        $typelessResponse->assertSee('https://www.typeless.com/?via=aihubb');

        // Fallback /ai/* paths continue to work as well
        $this->get('/ai/iapply')->assertStatus(200);
        $this->get('/ai/aiapply')->assertStatus(200);
        $this->get('/ai/anara')->assertStatus(200);
        $this->get('/ai/typeless')->assertStatus(200);
    }
}
